// Generates src/shared/api/schema.d.ts from openapi.json (run via `npm run api:types`).
// Same as the openapi-typescript CLI, except that file uploads are typed as Blob instead of
// string, so `api.POST(..., { body: { image: file } })` type-checks. FastAPI marks them with
// `contentMediaType: application/octet-stream` (OpenAPI 3.1; 3.0 used `format: binary`).
import { writeFileSync } from "node:fs";

import openapiTS, { astToString } from "openapi-typescript";
import ts from "typescript";

const BLOB = ts.factory.createTypeReferenceNode(ts.factory.createIdentifier("Blob"));

const ast = await openapiTS(new URL("../openapi.json", import.meta.url), {
  transform(schemaObject) {
    const isFile =
      schemaObject.format === "binary" ||
      ("contentMediaType" in schemaObject &&
        schemaObject.contentMediaType === "application/octet-stream");
    if (isFile) return BLOB;
    return undefined;
  },
});
writeFileSync(
  new URL("../src/shared/api/schema.d.ts", import.meta.url),
  "// Generated by scripts/generate-api-types.mjs from openapi.json. Do not edit.\n\n" +
    astToString(ast),
);
